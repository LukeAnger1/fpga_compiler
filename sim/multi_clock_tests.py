#!/usr/bin/env python3
# [treesource] This script tests the multi clock pipelines, new inputs are given every fast cycle to make sure the copies of the slow clocks work

import cocotb
import os
import re
import sys
import random
from pathlib import Path
from cocotb.triggers import Timer, RisingEdge, FallingEdge, ReadOnly
from cocotb.runner import get_runner

from pre_build.pipelines.vars import Var, VarType
from pre_build.pipelines.module_implementation.multi_clock import (
    MultiClockPipelineCompiler,
)

# cheap way to get the name of current file for runner:
test_file = os.path.basename(__file__).replace(".py", "")

MODULE_NAME = "test_multi_clock"
BIT_SIZE = 8
NUM_INPUTS = 40


async def generate_clock(clock_wire):
    while True:  # repeat forever
        clock_wire.value = 0
        await Timer(5, units="ns")
        clock_wire.value = 1
        await Timer(5, units="ns")


def expected(a: int, b: int, e: int) -> int:
    # Matches the pipeline in compile_pipeline
    c = a + b
    f = e + c
    g = f + c
    i = g + g
    return (i + a) % (1 << BIT_SIZE)


def output_name() -> str:
    # The output name is generated by migen so read it from the verilog
    proj_path = Path(__file__).resolve().parent.parent
    verilog = (proj_path / "hdl" / "tests_dont_use" / f"{MODULE_NAME}.v").read_text()
    names = re.findall(r"output reg \[\d+:0\] (\w+)", verilog)
    assert len(names) == 1, f"expected a single output, got {names}"
    return names[0]


@cocotb.test()
async def test(dut):
    from sim.test_multi_clock_runtime_constants import test_multi_clock_delay

    output = getattr(dut, output_name())

    dut.sys_rst.value = 0
    dut.a.value = 0
    dut.b.value = 0
    dut.e.value = 0
    cocotb.start_soon(generate_clock(dut.sys_clk))

    random.seed(0)
    inputs = [
        tuple(random.randrange(1 << BIT_SIZE) for _ in range(3))
        for _ in range(NUM_INPUTS)
    ]

    # A new input every fast cycle, the output for input t is checked delay cycles later
    for cycle in range(NUM_INPUTS + test_multi_clock_delay):
        await FallingEdge(dut.sys_clk)
        if cycle < NUM_INPUTS:
            a, b, e = inputs[cycle]
            dut.a.value = a
            dut.b.value = b
            dut.e.value = e

        input_index = cycle - test_multi_clock_delay
        if input_index >= 0:
            await ReadOnly()
            a, b, e = inputs[input_index]
            assert output.value == expected(a, b, e), (
                f"cycle {cycle} input {input_index}: got {int(output.value)} expected {expected(a, b, e)}"
            )


"""the code below should largely remain unchanged in structure, though the specific files and things
specified should get updated for different simulations.
"""


def runner():
    """Simulate the generate code modules using the Python runner."""
    hdl_toplevel_lang = os.getenv("HDL_TOPLEVEL_LANG", "verilog")
    sim = os.getenv("SIM", "icarus")
    proj_path = Path(__file__).resolve().parent.parent
    sys.path.append(str(proj_path / "sim" / "model"))
    sources = [
        proj_path / "hdl" / "tests_dont_use" / f"{MODULE_NAME}.v",
    ]  # grow/modify this as needed.
    hdl_toplevel = MODULE_NAME
    build_test_args = ["-Wall"]  # ,"COCOTB_RESOLVE_X=ZEROS"]
    parameters = {}
    sys.path.append(str(proj_path / "sim"))
    runner = get_runner(sim)
    runner.build(
        sources=sources,
        hdl_toplevel=hdl_toplevel,
        always=True,
        build_args=build_test_args,
        parameters=parameters,
        timescale=("1ns", "1ps"),
        waves=True,
    )
    run_test_args = []
    runner.test(
        hdl_toplevel=hdl_toplevel,
        test_module=test_file,
        test_args=run_test_args,
        waves=True,
    )


def compile_pipeline():
    module = MultiClockPipelineCompiler(MODULE_NAME)
    a = Var(module, VarType(BIT_SIZE, False, True, True, False, False), name="a")
    b = Var(module, VarType(BIT_SIZE, False, True, True, False, False), name="b")
    e = Var(module, VarType(BIT_SIZE, False, True, True, False, False, 2), name="e")

    # Fast clock
    c = a + b
    # 2x slower clock, two registers in a row
    d = c.change_register_width(2)
    f = e + d
    g = f + d
    # 4x slower clock
    h = g.change_register_width(4)
    i = h + h
    # Back to the fast clock
    j = i.change_register_width(1)
    k = j + a
    module.compile("hdl/tests_dont_use", [k])


if __name__ == "__main__":
    compile_pipeline()
    runner()
